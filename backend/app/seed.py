"""
Заполняет БД начальными данными: способы термообработки.
Запускать: flask seed

Коэффициенты основаны на данных:
- USDA Table of Cooking Yields for Meat and Poultry
- Food Standards Australia New Zealand weight change factors
- freefoodtips.com/food-shrinkage-chart
"""
from app import db
from app.models import CookingMethod


def seed_cooking_methods():
    methods = [
        # (название, коэффициент, описание)
        # Коэффициент = вес_после / вес_до
        # Мясо и птица теряют много воды и жира
        ("Без обработки",      1.00),  # сырой продукт
        ("Варка (мясо/птица)", 0.60),  # мясо теряет ~40% при варке (USDA)
        ("Варка (рыба)",       0.80),  # рыба теряет ~20% при варке
        ("Варка (овощи)",      0.92),  # овощи теряют мало: морковь 0.5%, капуста 8%
        ("Варка (крупы)",      2.50),  # крупы впитывают воду: рис x2.5, гречка x2.1
        ("Варка (бобовые)",    2.20),  # бобовые впитывают воду
        ("Варка (яйца)",       1.00),  # яйца не меняют вес
        ("Жарка (мясо/птица)", 0.65),  # мясо теряет 35-45% при жарке
        ("Жарка (рыба)",       0.80),  # рыба теряет ~20% при жарке
        ("Жарка (овощи)",      0.75),  # овощи теряют 25-35% при жарке
        ("Жарка (яйца)",       0.85),  # яйца теряют ~15%
        ("Запекание (мясо)",   0.65),  # мясо теряет ~35% при запекании
        ("Запекание (рыба)",   0.80),  # рыба теряет ~20%
        ("Запекание (овощи)",  0.73),  # овощи теряют ~27% при запекании
        ("Тушение (мясо)",     0.65),  # мясо теряет ~35% при тушении
        ("Тушение (овощи)",    0.79),  # овощи теряют ~21% при тушении
        ("Варка на пару",      0.90),  # щадящий режим, меньше потерь
        ("Гриль (мясо)",       0.68),  # мясо теряет ~32% на гриле (USDA)
        ("Гриль (рыба)",       0.82),  # рыба теряет ~18% на гриле
        ("Бланширование",      0.90),  # кратковременная обработка
        ("Сушка/дегидратация", 0.25),  # продукт теряет ~75% влаги
    ]
    for name, coeff in methods:
        if not CookingMethod.query.filter_by(name=name).first():
            db.session.add(CookingMethod(name=name, weight_coefficient=coeff))
    db.session.commit()
    print("Способы термообработки добавлены.")


def seed_egg_unit():
    """Устанавливает unit='pcs' и serving_weight=60 для яиц."""
    from app.models import Product
    eggs = Product.query.filter(
        Product.name.ilike('%egg%') | Product.name_ru.ilike('%яйц%')
    ).all()
    for e in eggs:
        e.unit = 'pcs'
        if not e.serving_weight:
            e.serving_weight = 60.0
    db.session.commit()
    print(f"Обновлено {len(eggs)} яичных продуктов.")
